-- Добавляет хранилище DOCX-документов в уже существующую базу отделения.
-- Выполнять отдельно для каждой базы: hirurgia, travma, neurohir и т.д.
-- Клиент также создаёт эти объекты при запуске (CaseDocumentRepository::EnsureSchema),
-- но миграция нужна для серверов, куда клиент ещё не заходил.

CREATE TABLE IF NOT EXISTS case_documents (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id bigint NOT NULL,
    kind text NOT NULL,
    version_no integer NOT NULL,
    file_name text NOT NULL,
    content bytea NOT NULL,
    sha256 text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS case_documents_version_uq
    ON case_documents(case_id, kind, version_no);

CREATE INDEX IF NOT EXISTS case_documents_lookup_idx
    ON case_documents(case_id, kind, created_at DESC);
