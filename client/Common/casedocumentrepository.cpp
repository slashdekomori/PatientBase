namespace {

bool SetError(QString* error, const QString& message)
{
    if (error) {
        *error = message;
    }
    return false;
}

QString HashOf(const QByteArray& content)
{
    return QString::fromLatin1(QCryptographicHash::hash(content, QCryptographicHash::Sha256).toHex());
}

qlonglong LockKey(int case_id, const QString& kind)
{
    return (static_cast<qlonglong>(case_id) << 32) ^ static_cast<uint>(qHash(kind));
}

} // namespace

CaseDocumentRepository::CaseDocumentRepository(const QSqlDatabase& database)
    : db_(database)
{
}

bool CaseDocumentRepository::EnsureSchema(QString* error) const
{
    if (!db_.isOpen() && !db_.open()) {
        return SetError(error, db_.lastError().text());
    }

    QSqlQuery query(db_);

    const QString create_table =
        "CREATE TABLE IF NOT EXISTS case_documents ("
        "id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
        "case_id bigint NOT NULL, "
        "kind text NOT NULL, "
        "version_no integer NOT NULL, "
        "file_name text NOT NULL, "
        "content bytea NOT NULL, "
        "sha256 text NOT NULL, "
        "created_at timestamptz NOT NULL DEFAULT now()"
        ")";
    if (!query.exec(create_table)) {
        return SetError(error, query.lastError().text());
    }
    query.finish();

    const QString create_version_index =
        "CREATE UNIQUE INDEX IF NOT EXISTS case_documents_version_uq "
        "ON case_documents(case_id, kind, version_no)";
    if (!query.exec(create_version_index)) {
        return SetError(error, query.lastError().text());
    }
    query.finish();

    const QString create_lookup_index =
        "CREATE INDEX IF NOT EXISTS case_documents_lookup_idx "
        "ON case_documents(case_id, kind, created_at DESC)";
    if (!query.exec(create_lookup_index)) {
        return SetError(error, query.lastError().text());
    }
    query.finish();

    return true;
}

bool CaseDocumentRepository::SaveVersion(int case_id,
                                          const QString& kind,
                                          const QString& file_name,
                                          const QByteArray& content,
                                          int* version_no,
                                          QString* error) const
{
    if (content.isEmpty()) {
        return SetError(error, "Документ пуст.");
    }

    if (!db_.isOpen() && !db_.open()) {
        return SetError(error, db_.lastError().text());
    }

    const QString hash = HashOf(content);
    if (!db_.transaction()) {
        return SetError(error, db_.lastError().text());
    }

    auto fail = [this, error](const QSqlQuery& query) {
        db_.rollback();
        return SetError(error, query.lastError().text());
    };

    QSqlQuery query(db_);

    query.prepare("SELECT pg_advisory_xact_lock(?)");
    query.addBindValue(LockKey(case_id, kind));
    if (!query.exec()) {
        return fail(query);
    }
    query.finish();

    query.prepare("SELECT version_no, sha256 FROM case_documents "
                  "WHERE case_id = ? AND kind = ? ORDER BY version_no DESC LIMIT 1");
    query.addBindValue(case_id);
    query.addBindValue(kind);
    if (!query.exec()) {
        return fail(query);
    }

    int next_version = 1;
    if (query.next()) {
        if (query.value(1).toString() == hash) {
            if (version_no) {
                *version_no = query.value(0).toInt();
            }
            db_.commit();
            return true;
        }
        next_version = query.value(0).toInt() + 1;
    }
    query.finish();

    query.prepare("INSERT INTO case_documents "
                  "(case_id, kind, version_no, file_name, content, sha256) "
                  "VALUES (?, ?, ?, ?, ?, ?)");
    query.addBindValue(case_id);
    query.addBindValue(kind);
    query.addBindValue(next_version);
    query.addBindValue(file_name);
    query.addBindValue(content);
    query.addBindValue(hash);
    if (!query.exec()) {
        return fail(query);
    }
    query.finish();

    query.prepare("DELETE FROM case_documents "
                  "WHERE case_id = ? AND kind = ? AND id NOT IN ("
                  "SELECT id FROM case_documents "
                  "WHERE case_id = ? AND kind = ? ORDER BY version_no DESC LIMIT 3)");
    query.addBindValue(case_id);
    query.addBindValue(kind);
    query.addBindValue(case_id);
    query.addBindValue(kind);
    if (!query.exec()) {
        return fail(query);
    }
    query.finish();

    if (!db_.commit()) {
        return SetError(error, db_.lastError().text());
    }

    if (version_no) {
        *version_no = next_version;
    }
    return true;
}

bool CaseDocumentRepository::SaveFileVersion(int case_id,
                                              const QString& kind,
                                              const QString& file_path,
                                              int* version_no,
                                              QString* error) const
{
    const QFileInfo info(file_path);
    if (!info.exists() || !info.isFile()) {
        return SetError(error, QString("Файл документа не найден:\n%1").arg(file_path));
    }
    if (info.size() <= 0) {
        return SetError(error, QString("Файл документа пуст:\n%1").arg(file_path));
    }

    QFile file(file_path);
    if (!file.open(QIODevice::ReadOnly)) {
        return SetError(error, file.errorString());
    }
    const QByteArray content = file.readAll();
    file.close();

    return SaveVersion(case_id, kind, info.fileName(), content, version_no, error);
}

std::optional<CaseDocumentRepository::DocumentVersion> CaseDocumentRepository::Latest(
    int case_id, const QString& kind, QString* error) const
{
    if (!db_.isOpen() && !db_.open()) {
        SetError(error, db_.lastError().text());
        return std::nullopt;
    }

    QSqlQuery query(db_);
    query.prepare("SELECT version_no, file_name, content, sha256, created_at "
                  "FROM case_documents WHERE case_id = ? AND kind = ? "
                  "ORDER BY version_no DESC LIMIT 1");
    query.addBindValue(case_id);
    query.addBindValue(kind);
    if (!query.exec()) {
        SetError(error, query.lastError().text());
        return std::nullopt;
    }
    if (!query.next()) {
        return std::nullopt;
    }

    DocumentVersion version;
    version.version_no = query.value(0).toInt();
    version.file_name = query.value(1).toString();
    version.content = query.value(2).toByteArray();
    version.sha256 = query.value(3).toString();
    version.created_at = query.value(4).toDateTime();
    return version;
}

std::vector<CaseDocumentRepository::DocumentVersion> CaseDocumentRepository::ListVersions(
    int case_id, const QString& kind, QString* error) const
{
    std::vector<DocumentVersion> result;

    if (!db_.isOpen() && !db_.open()) {
        SetError(error, db_.lastError().text());
        return result;
    }

    QSqlQuery query(db_);
    query.prepare("SELECT version_no, file_name, content, sha256, created_at "
                  "FROM case_documents WHERE case_id = ? AND kind = ? "
                  "ORDER BY version_no DESC");
    query.addBindValue(case_id);
    query.addBindValue(kind);
    if (!query.exec()) {
        SetError(error, query.lastError().text());
        return result;
    }

    while (query.next()) {
        DocumentVersion version;
        version.version_no = query.value(0).toInt();
        version.file_name = query.value(1).toString();
        version.content = query.value(2).toByteArray();
        version.sha256 = query.value(3).toString();
        version.created_at = query.value(4).toDateTime();
        result.push_back(std::move(version));
    }

    return result;
}
